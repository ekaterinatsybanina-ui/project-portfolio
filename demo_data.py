def seed(conn, today: date | None = None) -> None:
    """Очищает базу и заполняет синтетическими данными относительно `today`."""
    today = today or date.today()
    d = lambda off: (today + timedelta(days=off)).isoformat()
    db.clear_all(conn)
    for p in PROJECTS:
        conn.execute(
            "INSERT INTO projects (name, direction, owner, status, start_date, end_date,"
            " budget_plan, budget_fact, progress_fact, last_update) VALUES (?,?,?,?,?,?,?,?,?,?)",
            (p[0], p[1], p[2], p[3], d(p[4]), d(p[5]), p[6], p[7], p[8], d(-p[9])))
    for pid, title, off, done in MILESTONES:
        conn.execute("INSERT INTO milestones (project_id, title, due_date, done) VALUES (?,?,?,?)",
                     (pid, title, d(off), done))
    for e in EMPLOYEES:
        conn.execute("INSERT INTO employees (name, role, capacity_hours_week) VALUES (?,?,?)", e)
    for a in ASSIGNMENTS:
        conn.execute("INSERT INTO assignments (employee_id, project_id, hours_week) VALUES (?,?,?)", a)
    conn.commit()
